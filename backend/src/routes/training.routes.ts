import {Router} from 'express';
import {requireTrainer} from '../auth.js';
import {measurementCatalog,testCatalog} from '../catalog.js';
import {exercises} from '../exercises.js';
import * as controller from '../controllers/training.controller.js';
export const trainingRouter=Router();
trainingRouter.get('/catalog',(_req,res)=>res.json({measurements:measurementCatalog,tests:testCatalog}));
trainingRouter.get('/exercises',(_req,res)=>res.json({exercises}));
trainingRouter.get('/clients',controller.listClients);
trainingRouter.get('/clients/:id',controller.readClient);
trainingRouter.patch('/clients/:id',requireTrainer,controller.patchClient);
trainingRouter.get('/clients/:id/measurements',controller.listMeasurements);
trainingRouter.post('/clients/:id/measurements',requireTrainer,controller.addMeasurement);
trainingRouter.get('/clients/:id/assessments',controller.listAssessments);
trainingRouter.post('/clients/:id/assessments',requireTrainer,controller.addAssessment);
trainingRouter.get('/clients/:id/plans',controller.listPlans);
trainingRouter.post('/clients/:id/plans',requireTrainer,controller.addPlan);
trainingRouter.patch('/clients/:id/plans/:planId',requireTrainer,controller.patchPlan);
trainingRouter.post('/clients/:id/plans/:planId/approve',requireTrainer,controller.approvePlan);
trainingRouter.get('/clients/:id/sessions',controller.listSessions);
trainingRouter.post('/clients/:id/sessions',controller.addSession);
trainingRouter.patch('/clients/:id/sessions/:sessionId',controller.patchSession);
trainingRouter.get('/clients/:id/report',controller.report);
