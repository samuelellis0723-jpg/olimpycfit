import express from 'express';
import cookieParser from 'cookie-parser';
import cors from 'cors';
import { requireAuth } from './auth.js';
import { ApiError,errorHandler } from './errors.js';
import { authRouter } from './routes/auth.routes.js';
import { trainingRouter } from './routes/training.routes.js';
import { assistantRouter } from './routes/assistant.routes.js';
export const app=express();
app.disable('x-powered-by');
const allowedOrigins=new Set(['http://localhost:5173','http://127.0.0.1:5173',...(process.env.FRONTEND_ORIGIN?[process.env.FRONTEND_ORIGIN]:[])]);
app.use(cors({origin(origin,callback){callback(null,!origin || allowedOrigins.has(origin));},credentials:true}));
app.use((req,res,next)=>{res.setHeader('X-Content-Type-Options','nosniff');res.setHeader('Cache-Control','no-store'); if(!['GET','HEAD','OPTIONS'].includes(req.method)){const origin=req.get('origin');const site=req.get('sec-fetch-site');if((origin && !allowedOrigins.has(origin)) || site==='cross-site'){next(new ApiError(403,'INVALID_ORIGIN','El origen del envío no está permitido.'));return;}}next();});
app.use(express.json({limit:'64kb'}));app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({status:'ok',demo:true}));
app.use('/api/auth',authRouter);
app.use('/api/assistant',requireAuth,assistantRouter);
app.use('/api',requireAuth,trainingRouter);
app.use((_req,_res,next)=>next(new ApiError(404,'NOT_FOUND','Ruta no encontrada.')));
app.use(errorHandler);
