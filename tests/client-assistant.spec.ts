import { test, expect } from '@playwright/test';

test('Cliente registra y actualiza una sesión sin duplicar el calendario', async ({ page }, info) => {
  await page.request.post('/api/auth/login', { data: { email: 'client@demo.local', password: 'Demo123!' } });
  await page.goto('/client');
  await expect(page.locator('main')).toContainText('Ana');
  await page.goto('/client/routine');
  await page.getByRole('button', { name: 'SEMANA 01', exact: true }).click();
  await expect(page.locator('.workout-exercise').first()).toBeVisible();
  const date = await page.getByLabel('Fecha de la sesión', { exact: true }).inputValue();
  const initial = await (await page.request.get('/api/clients/client-ana/sessions')).json();
  const existingCount = initial.sessions.filter((s: { date: string }) => s.date === date).length;
  await page.getByRole('button', { name: 'Ver técnica ↗', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: 'Técnica e instrucciones', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Señales para detenerte', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar detalle de ejercicio', exact: true }).click();
  await page.getByRole('combobox', { name: 'Estado de la sesión', exact: true }).selectOption('completed');
  await page.getByRole('checkbox', { name: 'Completado', exact: true }).first().check();
  await page.getByLabel('Carga utilizada (kg)', { exact: true }).first().fill('12');
  await page.getByLabel(/^Esfuerzo percibido/).fill('6');
  await page.getByLabel(/^Fatiga percibida/).fill('4');
  await page.getByLabel(/^Motivación/).fill('8');
  const note = `Sesión revisada E2E ${info.project.name}`;
  await page.getByRole('textbox', { name: 'Observaciones de la sesión', exact: true }).fill(note);
  await page.getByRole('button', { name: /^(Guardar|Actualizar) sesión$/ }).click();
  await expect(page.getByRole('status')).toContainText(/Sesión guardada|sesión fue actualizada/);
  await page.reload();
  await expect(page.getByRole('textbox', { name: 'Observaciones de la sesión', exact: true })).toHaveValue(note);
  await page.getByRole('button', { name: 'Actualizar sesión', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('sin crear un registro adicional');
  const final = await (await page.request.get('/api/clients/client-ana/sessions')).json();
  expect(final.sessions.filter((s: { date: string }) => s.date === date).length).toBe(existingCount || 1);
  expect(final.sessions.some((s: { notes: string; rpe: number }) => s.notes === note && s.rpe === 6)).toBeTruthy();
  await page.goto('/client/history');
  await expect(page.getByRole('heading', { name: 'Historial de sesiones', exact: true })).toBeVisible();
  await page.screenshot({ path: `test-results/client-history-${info.project.name}.png`, fullPage: true });
});

test('Asistente simulado crea una propuesta sin publicarla', async ({ page }, info) => {
  await page.request.post('/api/auth/login', { data: { email: 'trainer@demo.local', password: 'Demo123!' } });
  await page.goto('/assistant');
  await expect(page.getByText('MODO DEMOSTRACIÓN', { exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Cliente de esta consulta', exact: true }).selectOption('client-ana');
  await page.getByRole('button', { name: 'Proponer un plan', exact: true }).click();
  const reply = page.waitForResponse(r => r.url().endsWith('/api/assistant') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Enviar consulta', exact: true }).click();
  const response = await reply;
  expect(response.ok()).toBeTruthy();
  const body = await response.json();
  expect(body.mode).toBe('demo');
  expect(body.proposal.status).toBe('draft');
  expect(body.proposal.weeks).toHaveLength(6);
  await expect(page.getByText('RESPUESTA SIMULADA · DEMOSTRACIÓN', { exact: true })).toBeVisible();
  await expect(page.getByText('BORRADOR · SIN PUBLICAR', { exact: true })).toBeVisible();
  await expect(page.getByRole('checkbox')).not.toBeChecked();
  await page.screenshot({ path: `test-results/assistant-${info.project.name}.png`, fullPage: true });
  await page.getByRole('link', { name: 'Revisar y editar propuesta', exact: true }).click();
  await expect(page).toHaveURL(/tab=plans/);
  const plans = await (await page.request.get('/api/clients/client-ana/plans')).json();
  expect(plans.plans.find((p: { id: string }) => p.id === body.proposal.id).status).toBe('draft');
});
